/** The locale key a browser language or URL value names, or null. */
export function matchLocale(value) {
  if (!value) return null;
  const tag = value.toLowerCase();
  if (tag.startsWith("ja")) return "ja";
  if (tag.startsWith("ko")) return "ko";
  if (tag.startsWith("vi")) return "vi";
  if (tag.startsWith("zh-hant") || tag.startsWith("zh-tw") || tag.startsWith("zh-hk") || tag.startsWith("zh-mo")) {
    return "zh-Hant";
  }
  if (tag === "zh" || tag.startsWith("zh-hans") || tag.startsWith("zh-cn") || tag.startsWith("zh-sg") || tag.startsWith("zh-my")) {
    return "zh-Hans";
  }
  if (tag.startsWith("en")) return "en";
  return null;
}
